/// Metadata for a registered workflow, generated by `#[workflow]`.
pub struct WorkflowInfo {
    /// Snake-case function name (e.g., `"onboarding_workflow"`).
    pub name: &'static str,
    /// `module_path!()` value from the macro call site.
    pub module: &'static str,
    /// Type-erased dispatch function.
    pub handler: WorkflowHandlerFn,
    /// Default maximum wall-clock lifetime for executions of this workflow type
    /// (issue #243). `None` means no deadline enforced unless overridden at the
    /// `start_workflow` call site. Per-call overrides always win over this default.
    pub execution_timeout: Option<Duration>,
    /// Optional per-key concurrency constraint declared via
    /// `#[workflow(concurrency(key = "input.tenant_id", limit = 10))]`.
    ///
    /// `None` = no per-key cap; only the worker-level semaphore applies.
    pub concurrency: Option<crate::concurrency::ConcurrencyPolicy>,
    /// Per-workflow-type override for the workflow-input size cap (issue #252).
    ///
    /// When set, this raises (never lowers) the global `max_workflow_input_bytes`
    /// configured on [`HarvestBuilder`](crate::builder::HarvestBuilder) for this
    /// specific workflow type. Declared via
    /// `#[workflow(max_input_bytes = "8MiB")]`.
    ///
    /// `None` means the global cap applies.
    pub max_input_bytes: Option<u64>,
    /// Team owner metadata (issue #372).
    pub owner: Option<&'static str>,
    /// Linked runbook URL metadata (issue #372).
    pub runbook_url: Option<&'static str>,
    /// Severity level metadata (issue #372).
    pub severity: Option<&'static str>,
    /// Optional human-readable description of this workflow's purpose.
    ///
    /// Set via `#[workflow(description = "…")]` or the [`with_description`](Self::with_description)
    /// builder method. Surfaced by `GET /workflows/registered` (issue #373).
    pub description: Option<&'static str>,
    /// Optional JSON Schema (as a generator function) describing the workflow's
    /// input type (issue #373). `None` means no schema is published; the start
    /// endpoint accepts any JSON value without validation.
    ///
    /// Set via [`with_input_schema_fn`](Self::with_input_schema_fn) or the
    /// `schema` feature's [`with_schemas`](Self::with_schemas) method.
    pub input_schema: Option<fn() -> serde_json::Value>,
    /// Optional JSON Schema describing the workflow's success output type.
    pub output_schema: Option<fn() -> serde_json::Value>,
    /// Optional JSON Schema describing the workflow's error type.
    pub error_schema: Option<fn() -> serde_json::Value>,
}

impl WorkflowInfo {
    /// Attach a human-readable description to this workflow.
    ///
    /// Fluent builder method — call after the companion function:
    /// ```rust,ignore
    /// .workflows(vec![onboarding_info().with_description("Handles new-user onboarding")])
    /// ```
    #[must_use]
    pub const fn with_description(mut self, desc: &'static str) -> Self {
        self.description = Some(desc);
        self
    }

    /// Attach a raw input-schema generator function.
    ///
    /// The function is called once per request to `GET /workflows/registered`
    /// and `GET /workflows/registered/{name}/schema`, and once per
    /// `POST /workflows/{name}/start` for input validation.
    #[must_use]
    pub const fn with_input_schema_fn(mut self, f: fn() -> serde_json::Value) -> Self {
        self.input_schema = Some(f);
        self
    }

    /// Attach a raw output-schema generator function.
    #[must_use]
    pub const fn with_output_schema_fn(mut self, f: fn() -> serde_json::Value) -> Self {
        self.output_schema = Some(f);
        self
    }

    /// Attach a raw error-schema generator function.
    #[must_use]
    pub const fn with_error_schema_fn(mut self, f: fn() -> serde_json::Value) -> Self {
        self.error_schema = Some(f);
        self
    }

    /// Validate a JSON value against this workflow's `input_schema` (if any).
    ///
    /// Returns `Ok(())` when:
    /// - no `input_schema` is set (opt-in: workflows without a schema are unconstrained), or
    /// - the input passes all schema constraints.
    ///
    /// Returns `Err(violations)` with at least one [`SchemaViolation`] when the
    /// input violates the schema. The `field_path` is a JSON Pointer (RFC 6901)
    /// to the offending field.
    ///
    /// Used by `POST /api/harvest/workflows/{name}/start` to reject bad inputs
    /// before they reach the worker (issue #373).
    ///
    /// # Errors
    ///
    /// Returns `Err(Vec<SchemaViolation>)` when the input fails schema validation.
    pub fn validate_input(&self, input: &serde_json::Value) -> Result<(), Vec<SchemaViolation>> {
        let Some(schema_fn) = self.input_schema else {
            return Ok(());
        };
        let schema = schema_fn();
        validate_against_schema(&schema, input)
    }

    /// Convenience method (enabled with the `schema` feature) that attaches
    /// JSON Schemas for `I` and `O` using [`schemars`].
    ///
    /// The error schema is always published as `{"type": "string"}` because the
    /// workflow runtime stringifies every `Err(e)` value before recording it in
    /// `WorkflowFailed`. Publishing the structured schema of `E` would mislead
    /// discovery clients into expecting a payload that can never be returned.
    ///
    /// # Example
    ///
    /// ```rust,ignore
    /// use autumn_harvest::prelude::*;
    /// use schemars::JsonSchema;
    ///
    /// #[derive(serde::Deserialize, serde::Serialize, JsonSchema)]
    /// struct OnboardInput { user_id: i64 }
    ///
    /// #[workflow(description = "New-user onboarding flow")]
    /// async fn onboarding(ctx: &WorkflowContext, input: OnboardInput) -> Result<(), String> {
    ///     Ok(())
    /// }
    ///
    /// // In the builder:
    /// .workflows(vec![
    ///     onboarding_info().with_schemas::<OnboardInput, ()>(),
    /// ])
    /// ```
    #[cfg(feature = "schema")]
    #[must_use]
    pub fn with_schemas<I, O>(self) -> Self
    where
        I: schemars::JsonSchema,
        O: schemars::JsonSchema,
    {
        fn schema_for<T: schemars::JsonSchema>() -> serde_json::Value {
            serde_json::to_value(schemars::schema_for!(T)).unwrap_or_default()
        }
        fn string_schema() -> serde_json::Value {
            serde_json::json!({"type": "string"})
        }
        self.with_input_schema_fn(schema_for::<I>)
            .with_output_schema_fn(schema_for::<O>)
            .with_error_schema_fn(string_schema)
    }
}

/// Validate `input` against a JSON Schema value.
///
/// Returns `Ok(())` on success or `Err(Vec<SchemaViolation>)` with at least one
/// entry on failure. Uses a simple structural walker so the core crate has no
/// mandatory dependency on a JSON Schema validator library.
///
/// # Errors
///
/// Returns `Err(Vec<SchemaViolation>)` when `input` violates the schema.
pub fn validate_against_schema(
    schema: &serde_json::Value,
    input: &serde_json::Value,
) -> Result<(), Vec<SchemaViolation>> {
    let mut violations: Vec<SchemaViolation> = Vec::new();
    validate_node(schema, schema, input, "", &mut violations);
    if violations.is_empty() {
        Ok(())
    } else {
        Err(violations)
    }
}

/// Recursive schema walker — validates `value` against `schema` at path `ptr`.
///
/// `root` is the top-level schema document, used to resolve `$ref` pointers.
#[allow(clippy::too_many_lines)]
fn validate_node(
    root: &serde_json::Value,
    schema: &serde_json::Value,
    value: &serde_json::Value,
    ptr: &str,
    out: &mut Vec<SchemaViolation>,
) {
    // Resolve $ref (local JSON Pointer only, e.g. "#/definitions/Foo").
    let mut schema = schema;
    let mut visited = std::collections::HashSet::new();
    while let Some(ref_str) = schema.get("$ref").and_then(|v| v.as_str()) {
        if !visited.insert(ref_str) {
            break; // cycle guard
        }
        if let Some(stripped) = ref_str.strip_prefix('#') {
            if let Some(resolved) = root.pointer(stripped) {
                schema = resolved;
            } else {
                break;
            }
        } else {
            break; // external refs not supported — skip
        }
    }

    let Some(schema_obj) = schema.as_object() else {
        return;
    };

    // field_path helper: returns None for the root, Some(ptr) otherwise.
    let path = || {
        if ptr.is_empty() {
            None
        } else {
            Some(ptr.to_string())
        }
    };

    // type check — handles both scalar "type": "string" and multi-type "type": ["string","null"]
    if let Some(type_node) = schema_obj.get("type") {
        let type_ok = type_node.as_str().map_or_else(
            || {
                type_node.as_array().is_none_or(|arr| {
                    arr.iter()
                        .filter_map(|v| v.as_str())
                        .any(|t| type_matches(t, value))
                })
            },
            |single| type_matches(single, value),
        );
        if !type_ok {
            let expected = type_node.to_string();
            out.push(SchemaViolation {
                message: format!("expected type {expected}, got '{}'", json_type_name(value)),
                field_path: path(),
            });
            return;
        }
    }

    // required fields
    if let (Some(required), Some(obj)) = (
        schema_obj.get("required").and_then(|v| v.as_array()),
        value.as_object(),
    ) {
        for req in required {
            if let Some(field) = req.as_str()
                && !obj.contains_key(field)
            {
                // Escape field name per RFC 6901: ~ → ~0, / → ~1.
                let escaped = field.replace('~', "~0").replace('/', "~1");
                out.push(SchemaViolation {
                    message: format!("missing required field '{field}'"),
                    field_path: Some(format!("{ptr}/{escaped}")),
                });
            }
        }
    }

    // properties — recurse
    if let (Some(properties), Some(obj)) = (
        schema_obj.get("properties").and_then(|v| v.as_object()),
        value.as_object(),
    ) {
        for (prop_name, prop_schema) in properties {
            if let Some(prop_value) = obj.get(prop_name) {
                // Escape property name per RFC 6901: ~ → ~0, / → ~1.
                let escaped_name = prop_name.replace('~', "~0").replace('/', "~1");
                let child_ptr = format!("{ptr}/{escaped_name}");
                validate_node(root, prop_schema, prop_value, &child_ptr, out);
            }
        }
    }

    // enum check
    if let Some(enum_vals) = schema_obj.get("enum").and_then(|v| v.as_array())
        && !enum_vals.contains(value)
    {
        out.push(SchemaViolation {
            message: "value is not one of the allowed enum values".to_string(),
            field_path: path(),
        });
    }

    // array items — recurse into each element
    if let (Some(items_schema), Some(arr)) = (schema_obj.get("items"), value.as_array()) {
        for (i, elem) in arr.iter().enumerate() {
            let child_ptr = format!("{ptr}/{i}");
            validate_node(root, items_schema, elem, &child_ptr, out);
        }
    }

    // minLength / maxLength for strings
    if let Some(s) = value.as_str() {
        let char_count = s.chars().count() as u64;
        if let Some(min) = schema_obj
            .get("minLength")
            .and_then(serde_json::Value::as_u64)
            && char_count < min
        {
            out.push(SchemaViolation {
                message: format!("string is shorter than minLength {min}"),
                field_path: path(),
            });
        }
        if let Some(max) = schema_obj
            .get("maxLength")
            .and_then(serde_json::Value::as_u64)
            && char_count > max
        {
            out.push(SchemaViolation {
                message: format!("string is longer than maxLength {max}"),
                field_path: path(),
            });
        }
    }

    // minimum / maximum for numbers
    if let Some(n) = value.as_f64() {
        if let Some(min) = schema_obj
            .get("minimum")
            .and_then(serde_json::Value::as_f64)
            && n < min
        {
            out.push(SchemaViolation {
                message: format!("value {n} is less than minimum {min}"),
                field_path: path(),
            });
        }
        if let Some(max) = schema_obj
            .get("maximum")
            .and_then(serde_json::Value::as_f64)
            && n > max
        {
            out.push(SchemaViolation {
                message: format!("value {n} is greater than maximum {max}"),
                field_path: path(),
            });
        }
    }

    // additionalProperties — reject unknown keys (false) or validate them against a sub-schema
    if let (Some(add_props), Some(obj)) =
        (schema_obj.get("additionalProperties"), value.as_object())
    {
        let known_keys: std::collections::HashSet<&str> = schema_obj
            .get("properties")
            .and_then(|v| v.as_object())
            .map(|props| props.keys().map(String::as_str).collect())
            .unwrap_or_default();
        if add_props.as_bool() == Some(false) {
            // boolean false: any unknown key is forbidden
            for key in obj.keys() {
                if !known_keys.contains(key.as_str()) {
                    let escaped = key.replace('~', "~0").replace('/', "~1");
                    out.push(SchemaViolation {
                        message: format!("additional property '{key}' is not allowed"),
                        field_path: Some(format!("{ptr}/{escaped}")),
                    });
                }
            }
        } else if add_props.is_object() {
            // schema object: validate each additional (non-properties) key against it
            for (key, val) in obj {
                if !known_keys.contains(key.as_str()) {
                    let escaped = key.replace('~', "~0").replace('/', "~1");
                    let child_ptr = format!("{ptr}/{escaped}");
                    validate_node(root, add_props, val, &child_ptr, out);
                }
            }
        }
    }

    // allOf — value must satisfy every sub-schema
    if let Some(all_of) = schema_obj.get("allOf").and_then(|v| v.as_array()) {
        for sub_schema in all_of {
            let mut sub_violations = Vec::new();
            validate_node(root, sub_schema, value, ptr, &mut sub_violations);
            out.extend(sub_violations);
        }
    }

    // anyOf — value must satisfy at least one sub-schema
    if let Some(any_of) = schema_obj.get("anyOf").and_then(|v| v.as_array()) {
        let satisfied = any_of.iter().any(|sub_schema| {
            let mut sub_violations = Vec::new();
            validate_node(root, sub_schema, value, ptr, &mut sub_violations);
            sub_violations.is_empty()
        });
        if !satisfied {
            out.push(SchemaViolation {
                message: "value does not match any of the allowed schemas (anyOf)".to_string(),
                field_path: path(),
            });
        }
    }

    // oneOf — value must satisfy exactly one sub-schema
    if let Some(one_of) = schema_obj.get("oneOf").and_then(|v| v.as_array()) {
        let matched = one_of
            .iter()
            .filter(|sub_schema| {
                let mut sub_violations = Vec::new();
                validate_node(root, sub_schema, value, ptr, &mut sub_violations);
                sub_violations.is_empty()
            })
            .count();
        if matched != 1 {
            out.push(SchemaViolation {
                message: format!(
                    "value matches {matched} of the allowed schemas (oneOf requires exactly 1)"
                ),
                field_path: path(),
            });
        }
    }
}

fn type_matches(expected_type: &str, value: &serde_json::Value) -> bool {
    match expected_type {
        "object" => value.is_object(),
        "array" => value.is_array(),
        "string" => value.is_string(),
        "number" => value.is_number(),
        // JSON Schema "integer": must be a number with no fractional part.
        "integer" => {
            value.as_i64().is_some()
                || value.as_u64().is_some()
                || value.as_f64().is_some_and(|f| f.fract() == 0.0)
        }
        "boolean" => value.is_boolean(),
        "null" => value.is_null(),
        _ => true,
    }
}

#[allow(clippy::missing_const_for_fn)]
fn json_type_name(v: &serde_json::Value) -> &'static str {
    match v {
        serde_json::Value::Null => "null",
        serde_json::Value::Bool(_) => "boolean",
        serde_json::Value::Number(_) => "number",
        serde_json::Value::String(_) => "string",
        serde_json::Value::Array(_) => "array",
        serde_json::Value::Object(_) => "object",
    }
}

/// Metadata for a registered activity, generated by `#[activity]`.
pub struct ActivityInfo {
    /// Snake-case function name.
    pub name: &'static str,
    /// `module_path!()` value from the macro call site.
    pub module: &'static str,
    /// Default retry policy (overridable at call site).
    pub default_retry_policy: Option<RetryPolicy>,
    /// Default start-to-close timeout.
    pub default_start_to_close: Option<Duration>,
    /// Default heartbeat timeout (`None` = disabled).
    pub default_heartbeat_timeout: Option<Duration>,
    /// Default schedule-to-start timeout.
    pub default_schedule_to_start: Option<Duration>,
    /// Default task queue name (`None` = `"default"`).
    pub default_queue: Option<&'static str>,
    /// Cluster-wide concurrency cap. `None` = no cap (only the worker-level
    /// `max_concurrent_activities` semaphore applies).
    pub max_concurrent: Option<u32>,
    /// Concurrency group key. Multiple activities sharing a key share the
    /// `max_concurrent` budget. Defaults to the activity's own name when
    /// `max_concurrent` is set and `concurrency_key` is not specified.
    pub concurrency_key: Option<&'static str>,
    /// When `true`, the worker runs this activity inline on the workflow task
    /// (never enqueued). Local activities must not set `heartbeat_timeout`,
    /// `schedule_to_start`, or `queue` — the macro enforces this at compile time.
    pub is_local: bool,
    /// Per-activity override for the activity-input size cap (issue #252).
    ///
    /// When set, this raises (never lowers) the global `max_activity_input_bytes`
    /// for this specific activity. Declared via
    /// `#[activity(max_input_bytes = "8MiB")]`.
    ///
    /// `None` means the global cap applies.
    pub max_input_bytes: Option<u64>,
    /// Per-activity override for the activity-result size cap (issue #252).
    ///
    /// When set, this raises (never lowers) the global `max_activity_result_bytes`
    /// for this specific activity. Declared via
    /// `#[activity(max_result_bytes = "8MiB")]`.
    ///
    /// `None` means the global cap applies.
    pub max_result_bytes: Option<u64>,
    /// Cluster-wide rate limit (requests per second). `None` = no rate limit.
    pub rate_limit_rps: Option<f64>,
    /// Cluster-wide rate limit burst capacity (tokens). `None` = no burst capability or equal to `rate_limit_rps`.
    pub rate_limit_burst: Option<f64>,
    /// Rate limit bucket key. Multiple activities sharing a key share the
    /// rate limit. Defaults to the activity's own name when rate limits are set.
    pub rate_limit_key: Option<&'static str>,
    /// Optional circuit-breaker policy (issue #369). When set, the worker
    /// fast-fails dispatches of this activity with a non-retryable
    /// `"CircuitOpen"` failure while the breaker is open. `None` retains
    /// today's behaviour (no breaker; the full retry policy applies). Declared
    /// via `#[activity(circuit_breaker = CircuitBreakerPolicy::new(...))]`.
    pub circuit_breaker: Option<crate::policy::CircuitBreakerPolicy>,
    /// Type-erased dispatch function.
    pub handler: ActivityHandlerFn,
}

/// Metadata for a registered DAG, generated by `#[dag]`.
pub struct DagInfo {
    /// Snake-case function name.
    pub name: &'static str,
    /// `module_path!()` value from the macro call site.
    pub module: &'static str,
    /// Optional schedule for automatic runs.
    pub schedule: Option<Schedule>,
    /// Whether the scheduler should backfill missed intervals.
    pub catchup: bool,
    /// Maximum number of active runs allowed at once.
    pub max_active_runs: u32,
    /// Default queue applied to tasks that do not override their queue.
    pub default_queue: Option<&'static str>,
    /// Builder function that populates a [`DagBuilder`].
    pub builder: fn(&mut DagBuilder),
    /// Lowered workflow handler, populated when the `unified-dag-execution`
    /// feature is enabled (issue #256 Step 1).
    ///
    /// `None` on the classic DAG execution path; `Some` when the feature is
    /// on so the runtime can route new DAG runs through `WorkflowInfo`
    /// without needing to look up the companion by name.
    pub workflow_handler: Option<WorkflowHandlerFn>,
    /// Maximum spread window for staggering schedule fires. `Duration::ZERO`
    /// disables jitter (default — today's behaviour).
    pub jitter: Duration,
    /// What to do when a new firing collides with a still-running execution.
    /// Defaults to [`OverlapPolicy::Skip`].
    pub overlap_policy: crate::policy::OverlapPolicy,
    /// Maximum buffered slots under [`OverlapPolicy::BufferAll`]. Default 100.
    pub buffer_all_max: u32,
    /// Team owner metadata (issue #372).
    pub owner: Option<&'static str>,
    /// Linked runbook URL metadata (issue #372).
    pub runbook_url: Option<&'static str>,
    /// Severity level metadata (issue #372).
    pub severity: Option<&'static str>,
}

impl DagInfo {
    /// Build an immutable DAG definition from this metadata.
    ///
    /// # Errors
    ///
    /// Returns [`DagBuildError`] if the builder creates an invalid graph.
    pub fn build_definition(&self) -> Result<DagDefinition, DagBuildError> {
        let mut dag = self
            .default_queue
            .map_or_else(DagBuilder::new, DagBuilder::with_default_queue);
        (self.builder)(&mut dag);
        dag.build()
    }

    /// Return a [`WorkflowSchedule`] that fires this DAG on its declared cron
    /// or interval via the unified workflow execution path (issue #256 Step 2).
    ///
    /// Returns `None` when either:
    /// - `workflow_handler` is `None` (unified-dag-execution feature is off), or
    /// - `schedule` is `None` (DAG has no automatic trigger).
    #[must_use]
    pub fn as_workflow_schedule(&self) -> Option<WorkflowSchedule> {
        self.workflow_handler?;
        let schedule = self.schedule.clone()?;
        Some(WorkflowSchedule {
            workflow_name: self.name.to_string(),
            dag_name: Some(self.name.to_string()),
            schedule,
            input: serde_json::Value::Null,
            catchup: self.catchup,
            max_active_runs: self.max_active_runs,
            paused: false,
            queue_name: self.default_queue.unwrap_or("default").to_string(),
            jitter: self.jitter,
            overlap_policy: self.overlap_policy,
            buffer_all_max: self.buffer_all_max,
            execution_timeout: None,
            calendar: None,
            skip_policy: crate::policy::SkipPolicy::Skip,
            consecutive_failure_limit: None,
        })
    }

    /// Return a [`WorkflowInfo`] that executes this DAG via the unified
    /// workflow execution path (issue #256 Step 1).
    ///
    /// Returns `None` when the `unified-dag-execution` feature is disabled and
    /// `workflow_handler` was not populated by the macro.
    #[must_use]
    pub fn as_workflow_info(&self) -> Option<WorkflowInfo> {
        self.workflow_handler.map(|handler| WorkflowInfo {
            name: self.name,
            module: self.module,
            handler,
            execution_timeout: None,
            concurrency: None,
            max_input_bytes: None,
            owner: self.owner,
            runbook_url: self.runbook_url,
            severity: self.severity,
            description: None,
            input_schema: None,
            output_schema: None,
            error_schema: None,
        })
    }
}

