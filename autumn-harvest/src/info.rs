#[cfg(test)]
mod tests {
    use super::*;
    use crate::policy::TriggerRule;

    #[test]
    fn workflow_info_fields_accessible() {
        let info = WorkflowInfo {
            name: "test_workflow",
            module: "my_app::workflows",
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
            execution_timeout: None,
        };
        assert_eq!(info.name, "test_workflow");
        assert!(info.execution_timeout.is_none());
    }

    #[test]
    fn workflow_info_execution_timeout_field_is_accessible() {
        let info = WorkflowInfo {
            name: "billing_reconciliation",
            module: "my_app::workflows",
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
            execution_timeout: Some(std::time::Duration::from_secs(86_400)),
        };
        assert_eq!(info.execution_timeout, Some(std::time::Duration::from_secs(86_400)));
    }

    #[test]
    fn activity_info_default_policy() {
        let info = ActivityInfo {
            name: "test_activity",
            module: "my_app::activities",
            default_retry_policy: None,
            default_start_to_close: None,
            default_heartbeat_timeout: None,
            default_schedule_to_start: None,
            default_queue: None,
            max_concurrent: None,
            concurrency_key: None,
            is_local: false,
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
        };
        assert!(info.default_retry_policy.is_none());
        assert_eq!(info.default_queue, None);
        assert!(info.max_concurrent.is_none());
        assert!(info.concurrency_key.is_none());
        assert!(!info.is_local);
    }

    #[test]
    fn activity_info_is_local_true() {
        let info = ActivityInfo {
            name: "compute_hash",
            module: "my_app::activities",
            default_retry_policy: None,
            default_start_to_close: Some(std::time::Duration::from_secs(10)),
            default_heartbeat_timeout: None,
            default_schedule_to_start: None,
            default_queue: None,
            max_concurrent: None,
            concurrency_key: None,
            is_local: true,
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
        };
        assert!(info.is_local);
        assert!(
            info.default_heartbeat_timeout.is_none(),
            "local activities must not have heartbeat_timeout"
        );
        assert!(
            info.default_schedule_to_start.is_none(),
            "local activities must not have schedule_to_start"
        );
        assert!(
            info.default_queue.is_none(),
            "local activities must not have a queue"
        );
    }

    #[test]
    fn activity_info_concurrency_fields() {
        let info = ActivityInfo {
            name: "send_email",
            module: "my_app::activities",
            default_retry_policy: None,
            default_start_to_close: None,
            default_heartbeat_timeout: None,
            default_schedule_to_start: None,
            default_queue: None,
            max_concurrent: Some(5),
            concurrency_key: Some("email"),
            is_local: false,
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
        };
        assert_eq!(info.max_concurrent, Some(5));
        assert_eq!(info.concurrency_key, Some("email"));
    }

    #[test]
    fn dag_info_builds_definition() {
        fn extract_users() {}
        fn load_users() {}

        fn build(dag: &mut DagBuilder) {
            let first = dag.activity(extract_users);
            let _second = dag.activity(load_users).upstream(&first);
        }

        let info = DagInfo {
            name: "daily_etl",
            module: "tests",
            schedule: Some(Schedule::Manual),
            catchup: false,
            max_active_runs: 1,
            default_queue: Some("etl-workers"),
            builder: build,
            workflow_handler: None,
            jitter: ::std::time::Duration::ZERO,
            overlap_policy: crate::policy::OverlapPolicy::Skip,
            buffer_all_max: 100,
        };

        let definition = info.build_definition().expect("dag should compile");
        assert_eq!(definition.tasks().len(), 2);
        assert_eq!(definition.execution_levels().len(), 2);
        assert_eq!(definition.tasks()[0].queue.as_deref(), Some("etl-workers"));
        assert_eq!(definition.tasks()[1].trigger_rule, TriggerRule::AllSuccess);

        assert!(
            info.as_workflow_info().is_none(),
            "as_workflow_info should return None when workflow_handler is None"
        );
    }
    #[test]
    fn info_debug_formats_correctly() {
        let workflow_info = WorkflowInfo {
            name: "test_wf",
            module: "test_mod",
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
            execution_timeout: None,
        };
        let debug_str = format!("{workflow_info:?}");
        assert!(debug_str.contains("WorkflowInfo"));
        assert!(debug_str.contains("test_wf"));

        let activity_info = ActivityInfo {
            name: "test_act",
            module: "test_mod",
            default_retry_policy: None,
            default_start_to_close: None,
            default_heartbeat_timeout: None,
            default_schedule_to_start: None,
            default_queue: None,
            max_concurrent: None,
            concurrency_key: None,
            is_local: false,
            handler: |_ctx, input| Box::pin(async move { Ok(input) }),
        };
        let debug_str = format!("{activity_info:?}");
        assert!(debug_str.contains("ActivityInfo"));
        assert!(debug_str.contains("test_act"));

        let dag_info = DagInfo {
            name: "test_dag",
            module: "test_mod",
            schedule: None,
            catchup: false,
            max_active_runs: 1,
            default_queue: None,
            builder: |_| {},
            workflow_handler: None,
            jitter: ::std::time::Duration::ZERO,
            overlap_policy: crate::policy::OverlapPolicy::Skip,
            buffer_all_max: 100,
        };
        let debug_str = format!("{dag_info:?}");
        assert!(debug_str.contains("DagInfo"));
        assert!(debug_str.contains("test_dag"));
    }
}
