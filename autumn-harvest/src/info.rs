/// Metadata for a registered DAG, generated by `#[dag]`.
pub struct DagInfo {
    /// Snake-case function name.
    pub name: &'static str,
    /// `module_path!()` value from the macro call site.
    pub module: &'static str,
    /// Optional schedule for automatic runs.
    pub schedule: Option<Schedule>,
    /// Whether the scheduler should backfill missed intervals.
    pub catchup: bool,
    /// Maximum number of active runs allowed at once.
    pub max_active_runs: u32,
    /// Default queue applied to tasks that do not override their queue.
    pub default_queue: Option<&'static str>,
    /// Builder function that populates a [`DagBuilder`].
    pub builder: fn(&mut DagBuilder),
    /// Lowered workflow handler, populated when the `unified-dag-execution`
    /// feature is enabled (issue #256 Step 1).
    ///
    /// `None` on the classic DAG execution path; `Some` when the feature is
    /// on so the runtime can route new DAG runs through `WorkflowInfo`
    /// without needing to look up the companion by name.
    pub workflow_handler: Option<WorkflowHandlerFn>,
    /// Maximum spread window for staggering schedule fires. `Duration::ZERO`
    /// disables jitter (default — today's behaviour).
    pub jitter: Duration,
    /// What to do when a new firing collides with a still-running execution.
    /// Defaults to [`OverlapPolicy::Skip`].
    pub overlap_policy: crate::policy::OverlapPolicy,
    /// Maximum buffered slots under [`OverlapPolicy::BufferAll`]. Default 100.
    pub buffer_all_max: u32,
    /// Team owner metadata (issue #372).
    pub owner: Option<&'static str>,
    /// Linked runbook URL metadata (issue #372).
    pub runbook_url: Option<&'static str>,
    /// Severity level metadata (issue #372).
    pub severity: Option<&'static str>,
    /// Whether this DAG is exposed as MCP tools (`#[dag(mcp)]`), mirroring
    /// `WorkflowInfo::mcp` (issue #597 follow-up). Only meaningful when the
    /// `unified-dag-execution` feature is on, since MCP exposure lowers the
    /// DAG onto its shadow `WorkflowInfo`.
    pub mcp: bool,
    /// A hard wall-clock deadline for the whole scheduled DAG run
    /// (`#[dag(execution_timeout = "4h")]`, issue #743). Propagated verbatim
    /// to the shadow [`WorkflowInfo::execution_timeout`] by
    /// [`DagInfo::as_workflow_info`] and enforced by the EXISTING #243
    /// `timeout::enforce_workflow_execution_timeouts` scanner -- no new
    /// scanner, no new event variant.
    pub execution_timeout: Option<Duration>,
    /// A soft SLA for the whole scheduled DAG run (`#[dag(sla = "3h")]`,
    /// issue #743). Propagated verbatim to the shadow
    /// [`WorkflowInfo::sla`] and observed by the EXISTING #487
    /// `timeout::enforce_workflow_sla_breaches` scanner, without altering the
    /// run's lifecycle. Clamped down to `execution_timeout` at start when
    /// declared larger than it.
    pub sla: Option<Duration>,
}

impl DagInfo {
    /// Build an immutable DAG definition from this metadata.
    ///
    /// # Errors
    ///
    /// Returns [`DagBuildError`] if the builder creates an invalid graph.
    pub fn build_definition(&self) -> Result<DagDefinition, DagBuildError> {
        let mut dag = self
            .default_queue
            .map_or_else(DagBuilder::new, DagBuilder::with_default_queue);
        (self.builder)(&mut dag);
        dag.build()
    }

    /// Opt this DAG into MCP tool exposure, mirroring
    /// [`WorkflowInfo::with_mcp`]. Equivalent to `#[dag(mcp)]`.
    #[must_use]
    pub const fn with_mcp(mut self) -> Self {
        self.mcp = true;
        self
    }

    /// Whether this DAG contains at least one signal-gate node (issue #746).
    ///
    /// A signal-capable DAG pauses on a named signal (`signal_gate` /
    /// `signal_gate_with_timeout`), so an MCP surface must keep the
    /// `signal_{dag}` tool available for it (issue #597 follow-up); an
    /// activity-only DAG never consumes a signal and suppresses that tool.
    ///
    /// Returns `false` when the builder produces an invalid graph (the DAG
    /// would already fail registration elsewhere), erring toward the
    /// activity-only classification.
    #[must_use]
    pub fn consumes_signals(&self) -> bool {
        self.build_definition()
            .is_ok_and(|def| def.tasks().iter().any(|task| task.signal.is_some()))
    }

    /// Return a [`WorkflowSchedule`] that fires this DAG on its declared cron
    /// or interval via the unified workflow execution path (issue #256 Step 2).
    ///
    /// Returns `None` when either:
    /// - `workflow_handler` is `None` (unified-dag-execution feature is off), or
    /// - `schedule` is `None` (DAG has no automatic trigger).
    #[must_use]
    pub fn as_workflow_schedule(&self) -> Option<WorkflowSchedule> {
        self.workflow_handler?;
        let schedule = self.schedule.clone()?;
        Some(WorkflowSchedule {
            workflow_name: self.name.to_string(),
            dag_name: Some(self.name.to_string()),
            schedule,
            input: serde_json::Value::Null,
            catchup: self.catchup,
            max_active_runs: self.max_active_runs,
            paused: false,
            queue_name: self.default_queue.unwrap_or("default").to_string(),
            jitter: self.jitter,
            overlap_policy: self.overlap_policy,
            buffer_all_max: self.buffer_all_max,
            execution_timeout: None,
            // DAGs carry no chain-scoped lifetime cap (issue #617).
            chain_execution_timeout: None,
            calendar: None,
            skip_policy: crate::policy::SkipPolicy::Skip,
            consecutive_failure_limit: None,
            end_at: None,
            max_runs: None,
            catchup_policy: None,
            retry_policy: None,
            all_writable_shards: false,
        })
    }

    /// Return a [`WorkflowInfo`] that executes this DAG via the unified
    /// workflow execution path (issue #256 Step 1).
    ///
    /// Returns `None` when the `unified-dag-execution` feature is disabled and
    /// `workflow_handler` was not populated by the macro.
    #[must_use]
    pub fn as_workflow_info(&self) -> Option<WorkflowInfo> {
        self.workflow_handler.map(|handler| WorkflowInfo {
            name: self.name,
            module: self.module,
            handler,
            // issue #743: propagate the DAG's declared execution_timeout/sla
            // onto the shadow WorkflowInfo so the SAME `deadline_at`/
            // `sla_deadline_at` resolution the #243/#487 scanners already
            // enforce for a `#[workflow]` applies identically to a unified
            // DAG run -- no new scanner, no new event variant (AC1/AC2/AC3/AC4).
            execution_timeout: self.execution_timeout,
            // DAGs carry no chain-scoped lifetime cap (issue #617).
            chain_execution_timeout: None,
            sla: self.sla,
            concurrency: None,

            debounce: None,
            batch: None,
            throttle: None,
            max_input_bytes: None,
            owner: self.owner,
            runbook_url: self.runbook_url,
            severity: self.severity,
            description: None,
            input_schema: None,
            output_schema: None,
            error_schema: None,
            retry_policy: None,
            // `#[dag(mcp)]` / `DagInfo::with_mcp()` opt-in (issue #601
            // follow-up): mirrors this DAG's own `mcp` flag onto the shadow
            // `WorkflowInfo`. The MCP generator (`mcp_tools::collect_descriptors`)
            // detects this is a DAG separately and routes its `start` tool
            // through the DAG trigger contract rather than generic workflow
            // start.
            mcp: self.mcp,
            // A DAG's dependency graph is already validated structurally by
            // `dag_unregistered_activity_failures` walking its real
            // `DagDefinition` tasks (issue #802 targets the *imperative* path),
            // so the shadow `WorkflowInfo` declares nothing and is skipped by
            // the workflow-declaration pass — it is never double-validated.
            declared_activities: None,
            declared_children: None,
        })
    }
}

