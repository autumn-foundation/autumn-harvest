//! Registration types returned by macro-generated companion functions.
//!
//! `#[workflow]` generates `__autumn_workflow_info_*() -> WorkflowInfo`.
//! `#[activity]` generates `__autumn_activity_info_*() -> ActivityInfo`.
//! `#[query]` generates `__autumn_query_handler_info_*() -> QueryHandlerInfo`.
//! `#[update]` generates `__autumn_update_handler_info_*() -> UpdateHandlerInfo`.
//! These are collected by `workflows![]`, `activities![]`, `queries![]`, `updates![]`.

use std::future::Future;
use std::pin::Pin;
use std::time::Duration;

use crate::dag::{DagBuildError, DagBuilder, DagDefinition};
use crate::policy::{RetryPolicy, Schedule, WorkflowSchedule};

/// Type-erased workflow handler.
///
/// Takes a `WorkflowContext` reference and serialized JSON input;
/// returns serialized JSON output (or an error string).
///
/// The macro wraps the user's typed function to handle
/// serialization/deserialization at the boundary.
pub type WorkflowHandlerFn =
    fn(
        &crate::context::WorkflowContext,
        serde_json::Value,
    ) -> Pin<Box<dyn Future<Output = Result<serde_json::Value, String>> + Send + '_>>;

/// Type-erased activity handler.
pub type ActivityHandlerFn =
    fn(
        &crate::context::ActivityContext,
        serde_json::Value,
    ) -> Pin<Box<dyn Future<Output = Result<serde_json::Value, String>> + Send + '_>>;

/// Type-erased synchronous query handler for declarative `#[query]` functions.
///
/// Takes a `WorkflowContext` reference for shared-state access and the
/// serialised JSON input; returns serialised JSON output or an error string.
/// Query handlers are synchronous — they inspect state without performing I/O.
pub type QueryHandlerFn =
    fn(&crate::context::WorkflowContext, serde_json::Value) -> Result<serde_json::Value, String>;

/// Type-erased async update handler for declarative `#[update]` functions.
///
/// Takes an `Arc<WorkflowContext>` (owned, `'static`) so the returned future
/// can capture the context by value and remain `Send + 'static`. The dispatch
/// wrapper generated by `#[update]` dereferences the Arc to `&WorkflowContext`
/// when calling the user function.
pub type UpdateHandlerFn =
    fn(
        std::sync::Arc<crate::context::WorkflowContext>,
        serde_json::Value,
    ) -> Pin<Box<dyn Future<Output = Result<serde_json::Value, String>> + Send>>;

/// Type-erased synchronous update validator for declarative `#[update]` functions.
///
/// Runs before the update is admitted to history. Returns `Ok(())` to admit or
/// `Err(reason)` to reject without writing any event.
pub type UpdateValidatorFn = fn(&serde_json::Value) -> Result<(), String>;

/// Metadata for a declarative query handler, generated by `#[query(workflow = "…")]`.
///
/// Collected by the `queries![…]` bang macro and registered on
/// [`HarvestBuilder`](crate::builder::HarvestBuilder) via `.queries(…)`.
#[derive(Clone)]
pub struct QueryHandlerInfo {
    /// The query name (the function name), used as the key in the query registry.
    pub name: &'static str,
    /// Workflow name this handler is associated with (value of `workflow = "…"`).
    pub workflow: &'static str,
    /// `module_path!()` at the declaration site.
    pub module: &'static str,
    /// Best-effort Rust type name for the input (e.g., `"StatusRequest"` or `"()"`).
    pub input_type_hint: &'static str,
    /// Best-effort Rust type name for the `Ok` return type (e.g., `"StatusResponse"`).
    pub output_type_hint: &'static str,
    /// Type-erased dispatch function.
    pub handler: QueryHandlerFn,
}

/// Metadata for a declarative update handler, generated by `#[update(workflow = "…")]`.
///
/// Collected by the `updates![…]` bang macro and registered on
