//! `cargo xtask check signals-clean-approval-example-determinism`: the port
//! of `scripts/check-signals-clean-approval-example-determinism.sh`.
//!
//! The guard fails if the "Clean Declarative `await_condition`" example
//! (`collect_approvals_clean`) of `docs/getting-started/04-signals.md`
//! regresses into one of two compile failures. A newcomer hit both while
//! copying it verbatim. HVG010 hard-blocks the bare
//! `futures::future::select` race. A plain counter captured across the whole
//! loop causes a borrow-check error (E0506).
//! `autumn-harvest/examples/collect_approvals.rs` is the real, CI-compiled
//! equivalent that this example should match.
//!
//! This guard compiles the pinned block with `cargo check`. It does not grep
//! for stand-in text patterns (PR #1700). E0506 is a property of the borrow
//! checker, not a syntax shape. A text heuristic for "a plain
//! `let mut approvals = 0`" or "a `Mutex::new(` somewhere nearby" is exactly
//! as gameable as it sounds. Rename the counter, give it a type annotation,
//! or leave an unrelated Mutex in scope after a refactor. The real bug then
//! returns while a substring check still passes.
//!
//! `cargo xtask audit doc-snippet-syntax` deliberately does not compile the
//! whole corpus, as its own module doc explains. It would need a scratch
//! crate per chapter-local combination of imports and features. For about 93
//! blocks across 16 files, that is a real cost in compile time and
//! dependencies. That tradeoff does not apply to ONE pinned block that was
//! broken before. The `lint` job already builds the crate with
//! `cargo clippy -p autumn-harvest`. The marginal cost is one more
//! `cargo check --example`, not a new category of cost.

use std::path::Path;
use std::process::ExitCode;

use smop::prelude::*;

use super::default_run::support::{self, Report, ScratchExample};
use crate::util;

const DOC: &str = "docs/getting-started/04-signals.md";
const EXAMPLE_NAME: &str = "_onramp_doc_check_signals_clean_approval";
const ATTRIBUTE: &str = "#[workflow(allow_nondeterministic_apis)]";

/// Arguments of `cargo xtask check signals-clean-approval-example-determinism`.
#[derive(Debug, Clone, Copy, Args)]
pub struct Args {}

/// Runs `cargo xtask check signals-clean-approval-example-determinism`.
pub fn run(_args: Args) -> Result<ExitCode> {
    let root = util::repo_root();
    let example =
        ScratchExample::claim(root.join(format!("autumn-harvest/examples/{EXAMPLE_NAME}.rs")));
    let report = evaluate(&root, |source| {
        example.write(source)?;
        support::cargo_merged(
            &root,
            &[
                "check",
                "--quiet",
                "-p",
                "autumn-harvest",
                "--example",
                EXAMPLE_NAME,
            ],
        )
    })?;
    Ok(report.emit())
}

/// Builds the example source around the pinned block.
fn render(code: &str) -> String {
    format!(
        "#![allow(clippy::all, clippy::pedantic, clippy::nursery, dead_code)]
// Generated by `cargo xtask check signals-clean-approval-example-determinism`
// from docs/getting-started/04-signals.md -- not checked in, not a real
// example. Edit the markdown, not this file.
use autumn_harvest::prelude::*;
use serde_json::{{Value, json}};

{code}

fn main() {{
    let _wfs = workflows![collect_approvals_clean];
}}
"
    )
}

/// Checks the chapter under `root`. `compile` writes and checks one source.
fn evaluate(root: &Path, compile: impl FnOnce(&str) -> Result<(bool, String)>) -> Result<Report> {
    let mut report = Report::new();
    let path = root.join(DOC);
    if !path.is_file() {
        report.fail(format!("{DOC}: not found"));
        return Ok(report);
    }

    // The example runs from its own attribute line to the close of its
    // fence. The window survives a body that grows or shrinks, because it
    // stops at the next fence line and not after a fixed line count.
    let code = support::window_from(&support::read_or_empty(&path), ATTRIBUTE);
    if code.is_empty() {
        report.fail(format!(
            "{DOC}: could not find the collect_approvals_clean example (looked for its {ATTRIBUTE} attribute line); has the chapter been restructured, or has the fix in this example been reverted? Update this guard to match."
        ));
        return Ok(report);
    }

    let (passed, output) = compile(&render(&code))?;
    if !passed {
        report.err(format!(
            "{DOC}: collect_approvals_clean does not compile against the real autumn-harvest crate. A newcomer who copies this exact block hits this error:"
        ));
        report.err("");
        report.err(output);
        report.err("");
        report.fail(
            "See autumn-harvest/examples/collect_approvals.rs for the real, compiling equivalent this example is meant to match (the allow_nondeterministic_apis opt-out and a Mutex-backed counter).",
        );
        return Ok(report);
    }

    report.out("OK: collect_approvals_clean compiles against the real autumn-harvest crate.");
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture(body: &str) -> smop::fs::TempDir {
        let dir = fs::temp_dir().expect("temp dir");
        let doc = dir.path().join(DOC);
        std::fs::create_dir_all(doc.parent().expect("parent")).expect("mkdir");
        std::fs::write(doc, body).expect("doc");
        dir
    }

    #[test]
    fn render_wraps_the_block_between_imports_and_main() {
        let dir = fixture(&format!(
            "```rust\n{ATTRIBUTE}\nasync fn collect_approvals_clean() {{}}\n```\n"
        ));
        let mut seen = String::new();
        let report = evaluate(dir.path(), |source| {
            seen = source.to_owned();
            Ok((true, String::new()))
        })
        .expect("evaluate");
        assert_eq!(report.code(), 0);
        assert!(seen.contains(
            "use serde_json::{Value, json};\n\n#[workflow(allow_nondeterministic_apis)]\nasync fn collect_approvals_clean() {}\n\nfn main() {\n    let _wfs = workflows![collect_approvals_clean];\n}\n"
        ));
    }

    #[test]
    fn a_compile_failure_names_the_real_example() {
        let dir = fixture(&format!("{ATTRIBUTE}\nx\n```\n"));
        let report =
            evaluate(dir.path(), |_| Ok((false, "error[E0506]: x".into()))).expect("evaluate");
        assert_eq!(report.code(), 1);
        assert!(report.stderr().contains("hits this error:\n\nerror[E0506]: x\n\nSee autumn-harvest/examples/collect_approvals.rs"));
    }

    #[test]
    fn a_reverted_fix_is_reported() {
        let dir = fixture("#[workflow]\nasync fn collect_approvals_clean() {}\n```\n");
        let report = evaluate(dir.path(), |_| panic!("no compile")).expect("evaluate");
        assert!(
            report
                .stderr()
                .contains("has the fix in this example been reverted?")
        );
    }
}
